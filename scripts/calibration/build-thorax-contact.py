"""Conservative convex support enclosure of exact pinned rib source vertices.
Not an anatomical soft-tissue boundary: a geometric nonpenetration safeguard.
"""
import json,re,hashlib,sys
from pathlib import Path
import numpy as np,trimesh
from scipy.special import logsumexp
cache=Path(sys.argv[1]if len(sys.argv)>1 else'/tmp/upper-limb-atlas')
manifest=json.loads(re.search(r'const V57_MANIFEST=Object.freeze\((\[.*?\])\);',Path('index.html').read_text()).group(1))
sources=[]
def load(file):
 b=(cache/file).read_bytes();sources.append({'file':file,'sha256':hashlib.sha256(b).hexdigest()});return np.asarray(trimesh.load_mesh(cache/file).vertices)
ribs=np.concatenate([load(x['file'])for x in manifest if x['group']=='ribs'])
scap=load('FMA13395.stl');normals=trimesh.creation.icosphere(subdivisions=2).vertices
direction=scap.mean(0)-ribs.mean(0);normals=normals[np.argsort(-(normals@direction))]
support=np.max(normals@ribs.T,axis=1);tau=.5
D=scap@normals.T-support;g=tau*(logsumexp(D/tau,axis=1)-np.log(len(normals)))
assert g.min()>0,'Reference scapula must remain feasible, never shift the atlas to fit the safeguard'
# Uniform source 6mm cells; retain the thorax-facing vertex of each occupied
# cell. Whole source geometry is retained for the independent validation.
cell=6.;keys=np.floor(scap/cell).astype(int);pick={}
for i,key in enumerate(map(tuple,keys)):
 if key not in pick or g[i]<g[pick[key]]:pick[key]=i
ids=list(pick.values());points=scap[ids]
r={'version':'0.76.0','sourceCommit':'2c83c698788cff57f6317bddcf712e7acfbea7d8','sources':sources,'method':'162 support halfspaces of all source rib vertices; conservative smooth log-mean-exp; source scapular 6mm cell minima','smoothingMm':tau,'residualScaleMm':.1,'sampleCellMm':cell,'normals':normals.tolist(),'supportsMm':support.tolist(),'scapularPointsMm':points.tolist(),'restMinSupportMm':float(g.min()),'sourceScapularVertices':len(scap),'sourceRibVertices':len(ribs),'clinicalValidation':False}
Path('anatomy/thorax-contact-data-v076.js').write_text('/* Generated by scripts/calibration/build-thorax-contact.py. BodyParts3D CC BY-SA2.1JP. */\nglobalThis.ThoraxContactDataV076='+json.dumps(r,separators=(',',':'))+';\n')
print(json.dumps({k:r[k]for k in ['restMinSupportMm','sourceScapularVertices','sourceRibVertices','sampleCellMm']}),len(points),flush=True)
