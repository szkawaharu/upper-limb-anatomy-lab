import assert from 'node:assert/strict';
await import('../engine/math.js');
await import('../scripts/experimental/levator-boundary-registry.js');
await import('../scripts/experimental/levator-harmonic-boundary.js');
const M=AnatomyMath,H=LevatorHarmonicBoundary;
const rest=[0,0,0,1,0,0,2,0,0,0,1,0,1,1,0,2,1,0,0,2,0,1,2,0,2,2,0,4,0,0,5,0,0,4,1,0];
const data={rest,faces:[0,1,3,1,4,3,1,2,4,2,5,4,3,4,6,4,7,6,4,5,7,5,8,7,9,10,11],origin:[0,2,6,8],insertion:[5],nearestC:[0,0,1,0,0,0,2,0,3,0,0,0]};
const h=H.prepare(data);
assert.equal(h.diagnostics.components.length,2);
assert.equal(h.diagnostics.unanchoredVertices,3);
assert(h.diagnostics.partitionError<1e-7);
const frame={q:M.qaxis([0,1,0],.7),p:[1,2,3],rest:[0,0,0]},bones=Object.fromEntries(h.reg.keys.map(k=>[k,frame]));
const B={rest:Float32Array.from(rest),weights:new Float32Array(rest.length/3).fill(.5)};
const state={binding:B,a:frame,b:frame};
const out=H.deform(state,h,bones);
for(let i=0;i<B.weights.length;i++)assert(M.len(M.sub(Array.from(out.slice(3*i,3*i+3)),M.apply(frame,rest.slice(3*i,3*i+3))))<1e-6);
for(const [j,k]of h.reg.keys.entries())bones[k]={...frame,p:[1,j,3]};
const moved=H.deform(state,h,bones);
for(const t of LevatorBoundaryRegistry.targets(rest,h.reg,bones))assert(M.len(M.sub(Array.from(moved.slice(3*t.i,3*t.i+3)),t.point))<1e-6);
console.log('PASS five-bone harmonic surface control: partition, exact pins, rigid invariance, explicit unanchored component');
